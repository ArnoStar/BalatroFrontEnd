export type TextKey = keyof typeof EN;

export function tr(key: TextKey, vars: Record<string, string | number> = {}): string {
  const lang = String(G.SETTINGS?.language ?? 'en-us');
  const table = lang.startsWith('ru') ? RU : EN;
  return table[key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

/** a mod's name or description in the game's language (its `loc`) */
export function loc_of(m: { name: string; description?: string; loc?: Record<string, { name?: string; description?: string }> }) {
  const lang = String(G.SETTINGS?.language ?? 'en-us');
  const t = m.loc?.[lang] ?? m.loc?.[lang.split(/[-_]/)[0]];
  return { name: t?.name ?? m.name, description: t?.description ?? m.description ?? '' };
}
